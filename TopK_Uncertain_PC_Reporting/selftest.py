#!/usr/bin/env python3
"""Re-run the shipped correctness tests (requires JDK 21, Python 3, numpy)."""
from pathlib import Path
import os,subprocess,sys
R=Path(__file__).resolve().parent

def run(cmd):subprocess.run(cmd,cwd=R,check=True)
run([sys.executable,str(R/'code/tests/run_tests.py')]);run([sys.executable,str(R/'verify_optimized.py')]);run([sys.executable,str(R/'verify_ablation.py')]);
T=R/'build/tests';T.mkdir(parents=True,exist_ok=True)
run(['javac','--release','21','-encoding','UTF-8','-cp',str(R/'topk-benchmark.jar'),'-d',str(T),str(R/'tests/OracleTest.java'),str(R/'tests/FractionDriver.java')]);
# Legacy fraction driver uses build/classes, generated by build.py; use the tested jar instead.
run(['java','-Xmx1g','-ea','-cp',str(R/'topk-benchmark.jar')+os.pathsep+str(T),'itufp.OracleTest']);
run([sys.executable,str(R/'tests/fraction_oracle.py')]);run([sys.executable,str(R/'verify_runner.py')]);run([sys.executable,str(R/'verify_publication.py')]);print('ALL TESTS PASSED')
